"""Rigor pass: baselines, seeds, uncertainty, ROC/PR, error analysis, difficulty sweep.

Added after v1.0 to answer the questions a reviewer asks of the 0.984
headline. It adds new numbers only: results_learn.json,
results_build.json and results_deep.json are not touched. Output goes
to level-3-deep/results_rigor.json.

Everything here is NumPy only, CPU, seeded, and runs in well under a
minute. All data is synthetic, generated by the same recipe as the
Learn make_dataset. With its default arguments, dataset_with_params
draws exactly the same random numbers as make_dataset, so it can also
report each defect's amplitude, width and start (make_dataset does not
return them). tests/test_rigor.py checks that the two generators match.

Usage: python level-3-deep/rigor.py
"""
